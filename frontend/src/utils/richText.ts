/**
 * 后端文案里的最小富文本渲染。
 *
 * ## 为什么需要它
 *
 * 后端有些给用户看的句子带 `**重点**` 标记（"**这不是错误**"这类）。
 * 不处理的话，界面上会**原样显示两个星号** —— 这个坑本项目在 v2.5.0 的
 * 关系核对卡片上踩过一次，截图才看出来。
 *
 * 为什么不引 markdown 库：我们只需要"加粗"这一个标记，为它加一个依赖不划算。
 * 为什么不在后端把 `**` 去掉：去掉之后那句话就没有重点了，而重点是这句话的全部价值。
 *
 * ## ⚠️ 必须先转义再换标签
 *
 * 文案里插的是**数据库里的人名 / 设备编码**（`issues` 的 detail 就是拼出来的）。
 * 直接 `v-html` 等于把库里的内容当 HTML 执行 —— 先转义 `< > &`，再只替换我们自己的标记。
 *
 * **这是唯一实现**：关系核对卡片（`RelationCheckCard.vue`）与问题中心
 * （`InsightsView.vue`）都用它。别在组件里各写一份 ——
 * 两份渲染器迟早只改一份，然后同一个后端字段在两个页面上长得不一样。
 */
export function richText(text: string | null | undefined): string {
  const escaped = (text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
  return escaped.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
}
