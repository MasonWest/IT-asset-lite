export type IconName = keyof typeof ICON_PATHS

/**
 * 是不是一个已登记的图标名。
 *
 * 给数据层用：`icon` 字段是自由字符串（库里的列是 VARCHAR），
 * 读到未知值时靠它判断该不该退回 `box`。
 */
export function isIconName(value: unknown): value is IconName {
  return typeof value === 'string' && value in ICON_PATHS
}

